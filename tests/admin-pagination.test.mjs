import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const html=readFileSync(new URL('../lib/admin-ui.html',import.meta.url),'utf8');
const source=html.slice(html.indexOf('let listPosts=[];'),html.indexOf('/* ---- Module select ---- */'));
const elements=new Map();
const $=selector=>{
  if(!elements.has(selector)) elements.set(selector,{value:'',textContent:'',innerHTML:'',hidden:false,disabled:false,listeners:{},addEventListener(type,fn){this.listeners[type]=fn;}});
  return elements.get(selector);
};
const context=vm.createContext({$,document:{querySelectorAll:()=>[...elements].filter(([key])=>key.startsWith('#filter-')).map(([,el])=>el)},esc:String,typeOf:()=>({color:'#000',glyph:'',label:''}),moduleColor:()=>'#000',hexA:()=>'',catLabel:()=>'',fmtDate:String});
vm.runInContext(source,context);
const posts=Array.from({length:23},(_,i)=>({file:'post-'+(i+1),title:'Bài '+(i+1),module:i<10?'Kho':'Bán hàng',version:'v1',date:'2026-10-20',draft:false,isNew:false}));
context.posts=posts;
vm.runInContext('listPosts=posts; renderList();',context);
const rows=()=>Array.from($('#list').innerHTML.matchAll(/data-edit="([^"]+)"/g),m=>m[1]);
const click=selector=>$(selector).listeners.click({});
const change=(key,value)=>{$('#filter-'+key).value=value; $('#list-filters').listeners.input({});};
assert.deepEqual(rows(),['post-1','post-2','post-3','post-4','post-5','post-6','post-7','post-8','post-9','post-10']);
assert.equal($('#btn-prev-page').disabled,true);
assert.equal($('#btn-next-page').disabled,false);
click('#btn-next-page');
assert.equal(rows()[0],'post-11');
assert.equal(rows().length,10);
click('#btn-next-page');
assert.deepEqual(rows(),['post-21','post-22','post-23']);
assert.equal($('#btn-next-page').disabled,true);
change('title','Bài 23');
assert.deepEqual(rows(),['post-23'],'Tìm kiếm phải thấy bài ngoài trang hiện tại');
assert.equal($('#btn-prev-page').disabled,true);
change('title','');
change('module','Bán hàng');
assert.deepEqual(rows(),['post-11','post-12','post-13','post-14','post-15','post-16','post-17','post-18','post-19','post-20']);
click('#btn-next-page');
assert.deepEqual(rows(),['post-21','post-22','post-23']);
vm.runInContext('listPosts=posts.slice(0,20); renderList();',context);
assert.equal(rows()[0],'post-11','Xoá hết trang cuối phải trở về trang hợp lệ');
assert.equal($('#btn-next-page').disabled,true);
change('title','không tồn tại');
assert.equal(rows().length,0);
assert.equal($('#list-pagination').hidden,true);
click('#btn-reset-list');
assert.equal(rows()[0],'post-1');
$('#list').listeners.click({target:{closest:()=>({dataset:{sort:'title'}})}});
assert.equal(rows()[0],'post-1');
click('#btn-next-page');
$('#list').listeners.click({target:{closest:()=>({dataset:{sort:'title'}})}});
assert.equal(rows()[0],'post-20','Đổi sắp xếp phải về trang đầu và sắp xếp toàn bộ');
vm.runInContext('listPosts=[]; renderList();',context);
assert.equal(rows().length,0);
assert.equal($('#list-pagination').hidden,true);
console.log('Phân trang admin: 10 bài/trang, tìm/lọc toàn bộ, sắp xếp, đặt lại và trang rỗng đều đạt');
